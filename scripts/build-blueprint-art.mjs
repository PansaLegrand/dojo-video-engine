// Build-time only: whitelist specific MIT showcase layers and retain the exact
// source digest. No project or model input can select a file or execute code.
import fs from "node:fs";
import { createHash } from "node:crypto";
const root = new URL("../", import.meta.url);
const selection = {
  orbit: ["company", "orbit-chapter-1-sculpture"],
  littleWorlds: ["city", "miniature-city"],
  precision: ["precision", "precision-instrument"],
  afterHours: ["festival", "disco-sculpture"],
  nightLeague: ["sports", "stadium-world"],
  deepField: ["cinema", "light-tunnel"],
  letterForm: [
    "type-motion",
    "elastic-top-rule",
    "elastic-bottom-rule",
    ...Array.from({ length: 7 }, (_, i) => "elastic-grid-" + i),
  ],
  fieldNotes: ["data-story", "data-1-header-rule", "data-1-footer-rule"],
  flow: [
    "software",
    "flow1-brandmark-a",
    "flow1-brandmark-b",
    "flow1-brandmark-c",
  ],
};
const art = {};
for (const [id, [source, ...ids]] of Object.entries(selection)) {
  const raw = fs.readFileSync(
    new URL("examples/creative-showcase/" + source + ".json", root),
  );
  const scene = JSON.parse(raw),
    byId = new Map();
  function visit(n) {
    byId.set(n.id, n);
    n.children?.forEach(visit);
  }
  scene.nodes.forEach(visit);
  const nodes = ids.map((key) => {
    const n = byId.get(key);
    if (!n) throw Error(key);
    return n;
  });
  art[id] = {
    source,
    sha256: createHash("sha256").update(raw).digest("hex"),
    nodes,
  };
}
const output =
  "// Generated by scripts/build-blueprint-art.mjs from MIT showcase JSON.\nexport const blueprintArt: Record<string, string> = {\n" +
  Object.entries(art)
    .map(
      ([id, source]) =>
        JSON.stringify(id) +
        ": " +
        JSON.stringify(JSON.stringify(source)) +
        ",",
    )
    .join("\n") +
  "\n};\n";
const dest = new URL("packages/presets/src/blueprint-art.generated.ts", root);
if (process.argv.includes("--check")) {
  if (fs.readFileSync(dest, "utf8") !== output)
    throw Error("Rebuild blueprint artwork");
} else fs.writeFileSync(dest, output);
