import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  verifyColorFrames,
  verifyTone,
  verifyAudioTimeline,
  verifyFrameMarkers,
  readFrameMarker,
} from "./media-content-oracle.mjs";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const req = createRequire(path.join(root, "tools/golden/package.json"));
const { chromium } = req("playwright");
const { createServer } = await import(pathToFileURL(req.resolve("vite")).href);
const output = path.resolve(
  process.env.MEDIA_EVIDENCE_DIR ??
    path.join(
      root,
      "test-results/media",
      new Date().toISOString().replace(/[:.]/g, "-"),
    ),
);
await mkdir(output, { recursive: true });
const run = (bin, args) =>
  execFileSync(bin, args, {
    encoding: null,
    maxBuffer: 32 * 1024 * 1024,
    stdio: ["ignore", "pipe", "pipe"],
  });
const report = {
  version: 1,
  commit: run("git", ["rev-parse", "HEAD"]).toString().trim(),
  node: process.version,
  platform: process.platform,
  arch: process.arch,
  dirty: run("git", ["status", "--porcelain"]).toString().trim().length > 0,
  ffmpeg: run("ffmpeg", ["-version"]).toString().split("\n")[0],
  passed: false,
  checks: [],
};
const source = path.join(output, "source.mp4");
let server, browser;
try {
  const raw = Buffer.alloc(160 * 90 * 3 * 90);
  for (let frame = 0; frame < 90; frame++) {
    const color = Math.floor(frame / 30);
    for (let y = 0; y < 90; y++)
      for (let x = 0; x < 160; x++) {
        const at = (frame * 160 * 90 + y * 160 + x) * 3;
        if (y >= 20) raw[at + color] = 255;
        else
          for (let bit = 0; bit < 7; bit++)
            if (
              y >= 2 &&
              y < 16 &&
              x >= 8 + bit * 20 &&
              x < 22 + bit * 20 &&
              frame & (1 << bit)
            )
              raw.fill(255, at, at + 3);
      }
  }
  const rawPath = path.join(output, "source.rgb");
  await writeFile(rawPath, raw);
  run("ffmpeg", [
    "-v",
    "error",
    "-y",
    "-f",
    "rawvideo",
    "-pixel_format",
    "rgb24",
    "-video_size",
    "160x90",
    "-framerate",
    "30",
    "-i",
    rawPath,
    "-f",
    "lavfi",
    "-i",
    "aevalsrc='if(lt(t,1),0.25*sin(2*PI*440*t),if(lt(t,2),0.5*sin(2*PI*880*t),0.125*sin(2*PI*220*t)))':s=48000:d=3",
    "-map",
    "0:v",
    "-map",
    "1:a",
    "-c:v",
    "libx264",
    "-preset",
    "ultrafast",
    "-pix_fmt",
    "yuv420p",
    "-c:a",
    "aac",
    "-b:a",
    "192k",
    "-threads",
    "1",
    "-movflags",
    "+faststart",
    source,
  ]);
  const sourceBytes = await readFile(source);
  report.fixture = {
    id: "F-01/F-02-frame-markers-v2",
    license: "MIT synthetic fixture generated by this repository",
    sha256: createHash("sha256").update(sourceBytes).digest("hex"),
    fps: 30,
    seconds: 3,
    width: 160,
    height: 90,
    sampleRate: 48000,
    colors: ["red", "lime", "blue"],
    markers: "7-bit source frame ID, 14px cells at x=8+20*bit, y=2..15",
    tones: [
      { hz: 440, amplitude: 0.25 },
      { hz: 880, amplitude: 0.5 },
      { hz: 220, amplitude: 0.125 },
    ],
    tolerances: { videoFrames: 1, gainDb: 0.75, frequencyRatio: 0.9 },
  };
  server = await createServer({
    root: path.join(root, "tools/golden"),
    logLevel: "error",
    server: { host: "127.0.0.1", port: 0 },
  });
  await server.listen();
  browser = await chromium.launch({ headless: true });
  report.browser = browser.version();
  const page = await browser.newPage();
  await page.goto(server.resolvedUrls.local[0]);
  const vfr = path.join(output, "source-vfr.mp4");
  run("ffmpeg", [
    "-v",
    "error",
    "-y",
    "-i",
    source,
    "-vf",
    "select='if(lt(t,1),not(mod(n,2)),1)'",
    "-fps_mode",
    "vfr",
    "-c:v",
    "libx264",
    "-preset",
    "ultrafast",
    "-c:a",
    "copy",
    "-threads",
    "1",
    vfr,
  ]);
  const frameMetadata = JSON.parse(
    run("ffprobe", [
      "-v",
      "error",
      "-select_streams",
      "v:0",
      "-show_entries",
      "frame=best_effort_timestamp_time",
      "-of",
      "json",
      vfr,
    ]).toString(),
  );
  const pts = frameMetadata.frames.map((f) =>
    Number(f.best_effort_timestamp_time),
  );
  const deltas = new Set(
    pts.slice(1).map((t, i) => Math.round((t - pts[i]) * 1000)),
  );
  if (deltas.size < 2)
    throw new Error("VFR fixture did not contain variable timestamps");
  report.fixture.variants = [];
  for (const sourceKind of ["cfr", "vfr"]) {
    const variantFile = sourceKind === "cfr" ? source : vfr;
    const variantBytes = await readFile(variantFile);
    report.fixture.variants.push({
      kind: sourceKind,
      file: path.basename(variantFile),
      sha256: createHash("sha256").update(variantBytes).digest("hex"),
      frameDeltaMs: sourceKind === "vfr" ? [...deltas] : [1000 / 30],
    });
    const src = await page.evaluate(
      (bytes) =>
        URL.createObjectURL(
          new Blob([Uint8Array.from(bytes)], { type: "video/mp4" }),
        ),
      Array.from(variantBytes),
    );
    for (const kind of ["trim", "split", "rate"]) {
      const frames = kind === "rate" ? 45 : 60,
        offset = kind === "rate" ? 0 : 0.5,
        rate = kind === "rate" ? 2 : 1;
      const node = (id, from, duration, videoStartTime) => ({
        id,
        type: "video",
        assetId: "source",
        from,
        duration,
        videoStartTime,
        playbackRate: rate,
        volume: 0.5,
        style: { width: "100%", height: "100%" },
      });
      const scene = {
        schemaVersion: 1,
        width: 160,
        height: 90,
        fps: 30,
        duration: frames,
        assets: { source: { id: "source", type: "video", src } },
        nodes:
          kind === "split"
            ? [node("first", 0, 30, 0.5), node("second", 30, 30, 1.5)]
            : [node("clip", 0, frames, offset)],
      };
      const previewFrames = [frames - 1, 0, 1, Math.floor(frames / 2)];
      const previewMarkers = [];
      for (const frame of previewFrames) {
        const preview = await page.evaluate(
          ({ scene, frame }) => window.renderGoldenFrame(scene, frame),
          { scene, frame },
        );
        const at =
          (Math.floor(preview.height / 2) * preview.width +
            Math.floor(preview.width / 2)) *
          4;
        verifyColorFrames(Buffer.from(preview.rgba.slice(at, at + 3)), {
          width: 1,
          height: 1,
          frames: 1,
          sourceOffset: offset + (frame / 30) * rate,
        });
        previewMarkers.push({
          frame,
          sourceFrame: readFrameMarker(preview.rgba, { channels: 4 }),
        });
      }
      const exported = await page.evaluate(
        (scene) => window.renderGoldenExportFile(scene),
        scene,
      );
      const portableScene = {
        ...scene,
        assets: {
          source: { ...scene.assets.source, src: path.basename(variantFile) },
        },
      };
      const sceneBytes = JSON.stringify(portableScene, null, 2) + "\n";
      await writeFile(
        path.join(output, sourceKind + "-" + kind + ".scene.json"),
        sceneBytes,
      );
      const file = path.join(output, sourceKind + "-" + kind + ".mp4");
      await writeFile(file, Buffer.from(exported.base64, "base64"));
      run("ffmpeg", ["-v", "error", "-i", file, "-f", "null", "-"]);
      const rgb = run("ffmpeg", [
        "-v",
        "error",
        "-i",
        file,
        "-map",
        "0:v:0",
        "-pix_fmt",
        "rgb24",
        "-f",
        "rawvideo",
        "-",
      ]);
      verifyColorFrames(rgb, {
        width: 160,
        height: 90,
        frames,
        sourceOffset: offset,
        rate,
      });
      verifyFrameMarkers(rgb, {
        frames,
        sourceOffset: offset,
        rate,
        sourcePts: sourceKind === "vfr" ? pts : undefined,
      });
      for (const preview of previewMarkers) {
        const decoded = readFrameMarker(rgb, { frame: preview.frame });
        if (preview.sourceFrame !== decoded)
          throw new Error("Preview/export source frame mismatch");
      }
      const audio = run("ffmpeg", [
        "-v",
        "error",
        "-i",
        file,
        "-map",
        "0:a:0",
        "-af",
        "pan=mono|c0=c0",
        "-ac",
        "1",
        "-ar",
        "48000",
        "-f",
        "f32le",
        "-",
      ]);
      const pcm = Float32Array.from({ length: audio.length / 4 }, (_, i) =>
        audio.readFloatLE(i * 4),
      );
      const tones =
        kind === "rate"
          ? [
              { start: 0.1, end: 0.3, frequency: 880, amplitude: 0.125 },
              { start: 0.6, end: 0.8, frequency: 1760, amplitude: 0.25 },
              { start: 1.1, end: 1.3, frequency: 440, amplitude: 0.0625 },
            ]
          : [
              { start: 0.1, end: 0.3, frequency: 440, amplitude: 0.125 },
              { start: 0.7, end: 0.9, frequency: 880, amplitude: 0.25 },
              { start: 1.7, end: 1.9, frequency: 220, amplitude: 0.0625 },
            ];
      const measurements = tones.map((t) => ({ ...t, ...verifyTone(pcm, t) }));
      const audioWindows = verifyAudioTimeline(pcm, {
        frames,
        sourceOffset: offset,
        rate,
      });
      const metadata = JSON.parse(
        run("ffprobe", [
          "-v",
          "error",
          "-show_streams",
          "-of",
          "json",
          file,
        ]).toString(),
      );
      const video = metadata.streams.find((s) => s.codec_type === "video");
      if (
        video.width !== 160 ||
        video.height !== 90 ||
        Math.abs(Number(video.duration) - frames / 30) > 1 / 30
      )
        throw new Error("Export dimensions/duration mismatch");
      report.checks.push({
        kind,
        sourceKind,
        frames,
        previewFrames,
        previewMarkers,
        audioWindows,
        measurements,
        sceneSha256: createHash("sha256").update(sceneBytes).digest("hex"),
        audioMeasurement: "first channel; no implicit downmix gain",
        file: path.basename(file),
        sha256: createHash("sha256")
          .update(await readFile(file))
          .digest("hex"),
        passed: true,
      });
      console.log(
        `PASS ${sourceKind} ${kind}: ${frames} decoded frames and 3 independent audio windows`,
      );
    }
    await page.evaluate((src) => URL.revokeObjectURL(src), src);
  }
  report.passed = true;
} catch (error) {
  report.error = error instanceof Error ? error.message : String(error);
  process.exitCode = 1;
} finally {
  await browser?.close();
  await server?.close();
  await writeFile(
    path.join(output, "report.json"),
    JSON.stringify(report, null, 2) + "\n",
  );
  console.log(
    JSON.stringify({
      report: path.join(output, "report.json"),
      passed: report.passed,
      error: report.error,
    }),
  );
}
